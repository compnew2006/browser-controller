#!/usr/bin/env node
// Generate data only; both peers keep their independent handshake validation.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXTENSION_PROTOCOL_VERSION, EXTENSION_PROTOCOL_CAPABILITIES, REQUIRED_EXTENSION_CAPABILITIES } from '../mcp-server/dist/protocol/capabilities.js';
import { ERROR_CODES } from '../mcp-server/dist/core/error-codes.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'extension/lib/generated-contract.js');
const output = `// Generated by scripts/generate-extension-contract.mjs; run npm run build.\n` +
  `export const EXTENSION_PROTOCOL_VERSION = ${JSON.stringify(EXTENSION_PROTOCOL_VERSION)};\n` +
  `export const EXTENSION_PROTOCOL_CAPABILITIES = Object.freeze(${JSON.stringify(EXTENSION_PROTOCOL_CAPABILITIES, null, 2)});\n` +
  `export const REQUIRED_DAEMON_CAPABILITIES = Object.freeze(${JSON.stringify(REQUIRED_EXTENSION_CAPABILITIES, null, 2)});\n` +
  `export const ERROR_CODES = Object.freeze(${JSON.stringify(ERROR_CODES, null, 2)});\n`;
writeFileSync(target, output, 'utf8');
console.error(`wrote ${target}`);
