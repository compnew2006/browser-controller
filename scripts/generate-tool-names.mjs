#!/usr/bin/env node
/**
 * Print the tool names of the registry, one per line, sorted.
 *
 * The wire layer checks a tool name against this list instead of importing the
 * tools layer, so the list has to be derived from the registry — never typed
 * by hand. It is read from the BUILT registry, because that is what the
 * daemon actually ships: run `npm run build` first.
 *
 *   node scripts/generate-tool-names.mjs           # the names, one per line
 *   node scripts/generate-tool-names.mjs --ts      # the generated module
 *   node scripts/generate-tool-names.mjs --out mcp-server/src/protocol/tool-names.ts
 *
 * The generated module is mcp-server/src/protocol/tool-names.ts. Regenerate it
 * with:
 *
 *   npm run build
 *
 * (--out writes the file itself, so the encoding stays UTF-8 whatever the
 * shell does with a redirect.)
 *
 * tests/protocol-tool-names.test.ts compares the checked-in list with the
 * registry from source, so a tool added without regenerating fails the suite.
 */
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = path.join(ROOT, 'mcp-server', 'dist', 'tools', 'registry.js');

if (!existsSync(REGISTRY)) {
  console.error(`${REGISTRY} is missing. Run \`npm run build\` first, then run this script again.`);
  process.exit(1);
}

const { allTools } = await import(pathToFileURL(REGISTRY).href);
const names = [...new Set(allTools.map((tool) => tool.name))].sort();

if (process.argv.includes('--ts')) {
  const entries = names.map((name) => `  '${name}',`).join('\n');
  process.stdout.write(`/**
 * GENERATED FILE — do not edit by hand.
 *
 * The names of the registered tools, sorted. Generated by
 * \`node scripts/generate-tool-names.mjs --ts\` from the built registry; run
 * \`npm run build\` first.
 *
 * The wire layer checks a tool name against this list instead of importing the
 * tools layer, so the transport does not depend on the tools. Regenerate this
 * file whenever the registry changes: tests/protocol-tool-names.test.ts fails
 * on any drift.
 */
export const TOOL_NAMES = Object.freeze([
${entries}
] as const);
`);
} else {
  const outIndex = process.argv.indexOf('--out');
  if (outIndex !== -1) {
    const target = process.argv[outIndex + 1];
    if (!target) {
      console.error('--out needs the path of the file to write.');
      process.exit(1);
    }
    const entries = names.map((name) => `  '${name}',`).join('\n');
    writeFileSync(target, `/**
 * GENERATED FILE — do not edit by hand.
 *
 * The names of the registered tools, sorted. Generated by
 * \`node scripts/generate-tool-names.mjs --ts\` from the built registry; run
 * \`npm run build\` first.
 *
 * The wire layer checks a tool name against this list instead of importing the
 * tools layer, so the transport does not depend on the tools. Regenerate this
 * file whenever the registry changes: tests/protocol-tool-names.test.ts fails
 * on any drift.
 */
export const TOOL_NAMES = Object.freeze([
${entries}
] as const);
`, 'utf8');
    console.error(`wrote ${target}`);
  } else {
    process.stdout.write(names.join('\n') + '\n');
  }
}
